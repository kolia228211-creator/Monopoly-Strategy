class Doc(BaseDocTemplate):
    def __init__(self, path, **kw):
        super().__init__(path, pagesize=A4, leftMargin=16*mm, rightMargin=16*mm, topMargin=15*mm, bottomMargin=15*mm,
                         title="Математика Монополії richup.io", author="Claude", **kw)
        fr = Frame(self.leftMargin, self.bottomMargin, self.width, self.height, id="f")
        self.addPageTemplates([PageTemplate("p", [fr], onPage=self._foot)])
    def _foot(self, c, d):
        if d.page == 1: return
        c.setFont("DV", 7); c.setFillColor(colors.grey)
        c.drawString(16*mm, 9*mm, "richup.io · Classic · математична модель (точні дані сервера + позначені заглушки)")
        c.drawRightString(A4[0]-16*mm, 9*mm, f"стор. {d.page}")
    def afterFlowable(self, f):
        if isinstance(f, Paragraph) and f.style.name in ("h1","h2"):
            lvl = 0 if f.style.name=="h1" else 1
            key = "h%d" % id(f)
            self.canv.bookmarkPage(key); self.canv.addOutlineEntry(f.getPlainText(), key, lvl, closed=lvl>0)
            self.notify("TOCEntry", (lvl, f.getPlainText(), self.page, key))

def tbl(rows, widths=None, head=1, zebra=True, fs=None, align_right_from=1, style_extra=()):
    data = [[x if hasattr(x,"wrap") else Paragraph(str(x), ST["cellb" if ri<head else "cell"]) for x in row] for ri,row in enumerate(rows)]
    t = Table(data, colWidths=widths, repeatRows=head)
    st = [("BACKGROUND",(0,0),(-1,head-1),LIGHT), ("LINEBELOW",(0,head-1),(-1,head-1),0.6,ACC),
          ("VALIGN",(0,0),(-1,-1),"MIDDLE"), ("TOPPADDING",(0,0),(-1,-1),1.6), ("BOTTOMPADDING",(0,0),(-1,-1),1.6),
          ("LEFTPADDING",(0,0),(-1,-1),3), ("RIGHTPADDING",(0,0),(-1,-1),3)]
    if zebra:
        for i in range(head, len(rows)):
            if (i-head)%2: st.append(("BACKGROUND",(0,i),(-1,i),colors.HexColor("#F7F9FB")))
    t.setStyle(TableStyle(st+list(style_extra))); return t

